"""penkit — HTML report built from summary.json.

    index.html           overview (no detail)
    reports.html         one block per tool, with links to each report
    tools/<tool>.html    detailed results of one tool
    assets/penkit.css    shared styles (light / dark)

Static pages, no JavaScript and no external resource: the report opens offline.
"""
from __future__ import annotations

import datetime as dt
import html
import json
from pathlib import Path

TOOLS = {
    "betterleaks": {
        "name": "Betterleaks", "category": "Secrets",
        "covers": "Hard-coded API keys, tokens, passwords and private keys, in the repository files "
                  "and in the whole git history (CWE-798).",
    },
    "semgrep": {
        "name": "Semgrep", "category": "Source code (SAST)",
        "covers": "Flaws in the app code: SQL and command injection, XSS, path traversal, SSRF, "
                  "eval and unsafe deserialization, weak crypto, misconfiguration written in the code.",
    },
    "osv-scanner": {
        "name": "OSV-Scanner", "category": "Dependencies (CVE)",
        "covers": "Known vulnerabilities and malicious packages in the dependencies declared by the lockfiles, "
                  "checked against the OSV.dev database.",
    },
    "noir-zap": {
        "name": "Noir + ZAP", "category": "Running app (DAST)",
        "covers": "Noir maps the API routes from the code; ZAP attacks each of them on the running app: "
                  "injections, reflected XSS, security headers, CORS, exposed files.",
    },
}

NOT_COVERED = ("IDOR and business logic, routes behind authentication (not configured in ZAP), "
               "Docker configuration and infrastructure.")

SEVERITIES = [
    ("critical", "Critical"), ("high", "High"), ("medium", "Medium"),
    ("low", "Low"), ("info", "Info"), ("unknown", "Unrated"),
]
SEV_LABEL = dict(SEVERITIES)
SEV_RANK = {k: i for i, (k, _) in enumerate(SEVERITIES)}
STATUS = {
    "ok": ("Clear", "Nothing to report"),
    "findings": ("To review", "Some results need review"),
    "error": ("Error", "The tool could not finish"),
    "skipped": ("Not run", "Scan not executed"),
}
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August",
          "September", "October", "November", "December"]


def e(s) -> str:
    return html.escape(str(s if s is not None else ""), quote=True)


def safe_href(url: str) -> str:
    return e(url) if str(url).startswith(("http://", "https://")) else ""


def counts(findings: list[dict]) -> dict[str, int]:
    c = {k: 0 for k, _ in SEVERITIES}
    for f in findings:
        c[f.get("severity", "unknown") if f.get("severity") in c else "unknown"] += 1
    return c


def fmt_date(iso: str) -> str:
    try:
        d = dt.datetime.fromisoformat(iso)
    except (TypeError, ValueError):
        return e(iso)
    return f"{MONTHS[d.month - 1]} {d.day}, {d.year}, {d:%H:%M}"


def fmt_duration(s: float) -> str:
    s = int(round(s))
    return f"{s // 60} min {s % 60:02d} s" if s >= 60 else f"{s} s"


def plural(n: int, one: str, many: str) -> str:
    return f"{n} {one if n == 1 else many}"


# ───────────────────────────── layout ─────────────────────────────

def page(title: str, body: str, depth: int, active: str, s: dict) -> str:
    up = "../" * depth
    current = ' aria-current="page"'
    nav = "".join(
        f'<a href="{up}{href}"{current if key == active else ""}>{label}</a>'
        for key, href, label in [("index", "index.html", "Overview"), ("reports", "reports.html", "Reports by tool")])
    p = s["project"]
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)}</title>
<link rel="stylesheet" href="{up}assets/penkit.css">
</head>
<body>
<header class="top">
  <div class="wrap top-in">
    <a class="brand" href="{up}index.html"><span class="mark" aria-hidden="true"></span>penkit</a>
    <span class="top-project">{e(p['name'])}</span>
    <nav>{nav}</nav>
  </div>
</header>
<main class="wrap">
{body}
</main>
<footer class="wrap foot">
  Generated by penkit {e(s.get('penkit_version', ''))} on {fmt_date(s.get('finished', ''))} ·
  {' · '.join(e(TOOLS[t['id']]['name'] + ' ' + t.get('version', '')) for t in s['tools'] if t['id'] != 'noir-zap')}
  {''.join(' · ' + e(t.get('version', '')) for t in s['tools'] if t['id'] == 'noir-zap')}
</footer>
</body>
</html>
"""


def pill(status: str) -> str:
    label, title = STATUS.get(status, (status, ""))
    return f'<span class="pill st-{e(status)}" title="{e(title)}">{e(label)}</span>'


def sev_badge(sev: str) -> str:
    return f'<span class="sev sev-{e(sev)}">{e(SEV_LABEL.get(sev, sev))}</span>'


def sev_bar(c: dict[str, int]) -> str:
    total = sum(c.values())
    if not total:
        return '<div class="bar bar-empty" aria-hidden="true"></div>'
    segs = "".join(f'<span class="seg sev-bg-{k}" style="flex:{c[k]}" title="{e(SEV_LABEL[k])}: {c[k]}"></span>'
                   for k, _ in SEVERITIES if c[k])
    return f'<div class="bar" role="img" aria-label="{e(", ".join(f"{SEV_LABEL[k]} {c[k]}" for k, _ in SEVERITIES if c[k]))}">{segs}</div>'


def project_meta(s: dict) -> str:
    p = s["project"]
    bits = []
    if p.get("branch"):
        bits.append(f"branch <code>{e(p['branch'])}</code>")
    if p.get("commit"):
        bits.append(f"commit <code>{e(p['commit'])}</code>" + (' <span class="dirty">+ uncommitted changes</span>' if p.get("dirty") else ""))
    bits.append(f"app <code>{e(s.get('target_url', ''))}</code>")
    bits.append(fmt_date(s.get("started", "")))
    return " · ".join(bits)


# ───────────────────────────── overview ─────────────────────────────

def verdict(s: dict, total: dict[str, int]) -> tuple[str, str, str]:
    errors = [TOOLS[t["id"]]["name"] for t in s["tools"] if t["status"] == "error"]
    skipped = [TOOLS[t["id"]]["name"] for t in s["tools"] if t["status"] == "skipped"]
    worst = next((k for k, _ in SEVERITIES if total[k] and k not in ("info",)), None)
    n_act = sum(total[k] for k in ("critical", "high", "medium", "low", "unknown"))
    if worst in ("critical", "high"):
        tone = "bad"
        head = plural(total["critical"] + total["high"], "critical or high issue to fix first",
                      "critical or high issues to fix first")
    elif n_act:
        tone = "warn"
        head = plural(n_act, "issue to review", "issues to review") + ", none critical or high"
    else:
        tone = "good"
        head = "No issue found"
    sub = []
    if errors:
        tone = "bad" if tone != "bad" else tone
        sub.append(f"Incomplete analysis: {', '.join(errors)} failed.")
    if skipped:
        sub.append(f"Not run: {', '.join(skipped)}.")
    if not sub:
        sub.append(f"{plural(len(s['tools']), 'tool', 'tools')} ran to completion.")
    return tone, head, " ".join(sub)


def build_index(s: dict) -> str:
    total = counts([f for t in s["tools"] for f in t["findings"]])
    tone, head, sub = verdict(s, total)
    strip = "".join(
        f'<div class="count{" zero" if not total[k] else ""}"><span class="num sev-fg-{k}">{total[k]}</span>'
        f'<span class="lbl">{e(lbl)}</span></div>'
        for k, lbl in SEVERITIES if k != "unknown" or total[k])
    cards = []
    for t in s["tools"]:
        meta = TOOLS[t["id"]]
        cards.append(f"""
  <a class="card" href="reports.html#{e(t['id'])}">
    <div class="card-head"><span class="cat">{e(meta['category'])}</span>{pill(t['status'])}</div>
    <h3>{e(meta['name'])}</h3>
    <p class="card-sum">{e(t['summary'])}</p>
    {sev_bar(counts(t['findings']))}
    <span class="more">View report →</span>
  </a>""")
    dur = sum(t.get("duration_s", 0) for t in s["tools"])
    body = f"""
<section class="hero">
  <p class="eyebrow">Security audit</p>
  <h1>{e(s['project']['name'])}</h1>
  <p class="meta">{project_meta(s)}</p>
</section>

<section class="verdict tone-{tone}">
  <p class="v-head">{e(head)}</p>
  <p class="v-sub">{e(sub)} Total duration: {fmt_duration(dur)}.</p>
</section>

<section class="counts" aria-label="Results by severity">{strip}</section>

<section class="cards">{''.join(cards)}
</section>

<p class="scope"><strong>Outside the scope of these tools:</strong> {e(NOT_COVERED)}</p>
"""
    return page(f"Audit {s['project']['name']}", body, 0, "index", s)


# ───────────────────────────── reports by tool ─────────────────────────────

def links(t: dict, up: str = "", with_detail: bool = True) -> str:
    items = [f'<a class="btn primary" href="{up}tools/{e(t["id"])}.html">Detailed penkit report</a>'] if with_detail else []
    order = {"native": 0, "json": 1, "log": 2}
    for r in sorted(t.get("reports", []), key=lambda r: order.get(r["kind"], 1)):
        cls = "btn native" if r["kind"] == "native" else "btn"
        items.append(f'<a class="{cls}" href="{up}{e(r["path"])}">{e(r["label"])}</a>')
    return f'<div class="links">{"".join(items)}</div>'


def build_reports(s: dict) -> str:
    blocks = []
    for t in s["tools"]:
        meta = TOOLS[t["id"]]
        c = counts(t["findings"])
        notes = "".join(f"<li>{e(n)}</li>" for n in t.get("notes", []))
        cmds = "\n".join(e(x) for x in t.get("commands", []))
        chips = "".join(f'<span class="chip">{sev_badge(k)} {c[k]}</span>' for k, _ in SEVERITIES if c[k])
        blocks.append(f"""
<section class="tool" id="{e(t['id'])}">
  <div class="tool-head">
    <div><span class="cat">{e(meta['category'])}</span><h2>{e(meta['name'])}</h2></div>
    {pill(t['status'])}
  </div>
  <p class="tool-sum">{e(t['summary'])}</p>
  {f'<div class="chips">{chips}</div>' if chips else ''}
  <p class="covers">{e(meta['covers'])}</p>
  {links(t)}
  {f'<ul class="notes">{notes}</ul>' if notes else ''}
  <dl class="facts">
    <dt>Version</dt><dd>{e(t.get('version', ''))}</dd>
    <dt>Duration</dt><dd>{fmt_duration(t.get('duration_s', 0))}</dd>
  </dl>
  <details><summary>Commands run</summary><pre>{cmds}</pre></details>
</section>""")
    body = f"""
<section class="hero small">
  <p class="eyebrow">Reports by tool</p>
  <h1>{e(s['project']['name'])}</h1>
  <p class="meta">{project_meta(s)}</p>
</section>
{''.join(blocks)}
"""
    return page(f"Reports — {s['project']['name']}", body, 0, "reports", s)


# ───────────────────────────── tool detail ─────────────────────────────

def findings_table(findings: list[dict]) -> str:
    if not findings:
        return '<p class="empty">No results.</p>'
    rows = []
    for f in sorted(findings, key=lambda f: (SEV_RANK.get(f.get("severity"), 99), f.get("title", ""))):
        tags = "".join(f'<span class="tag">{e(x)}</span>' for x in f.get("tags", []) if x)
        if f.get("source"):
            tags += f'<span class="tag">{e(f["source"])}</span>'
        ref = safe_href(f.get("ref", ""))
        uris = f.get("uris") or []
        more = ("<details class=\"uris\"><summary>" + plural(len(uris), "affected URL", "affected URLs") +
                "</summary><ul>" + "".join(f"<li><code>{e(u)}</code></li>" for u in uris) + "</ul></details>") if len(uris) > 1 else ""
        rows.append(f"""
    <tr>
      <td class="c-sev">{sev_badge(f.get('severity', 'unknown'))}</td>
      <td>
        <div class="f-title">{e(f.get('title', ''))}</div>
        <div class="f-loc"><code>{e(f.get('location', ''))}</code></div>
        {f'<p class="f-detail">{e(f["detail"])}</p>' if f.get('detail') else ''}
        {f'<div class="tags">{tags}</div>' if tags else ''}
        {more}
        {f'<a class="f-ref" href="{ref}" rel="noreferrer noopener" target="_blank">Reference ↗</a>' if ref else ''}
      </td>
    </tr>""")
    return f'<table class="findings"><thead><tr><th>Severity</th><th>Result</th></tr></thead><tbody>{"".join(rows)}</tbody></table>'


def tool_extra(t: dict) -> str:
    x = t.get("extra", {})
    if t["id"] == "semgrep" and x:
        return (f'<p class="ctx">{plural(x.get("files_scanned", 0), "file", "files")} scanned · rulesets '
                + ", ".join(f"<code>{e(r)}</code>" for r in x.get("rulesets", [])) + "</p>")
    if t["id"] == "osv-scanner" and x.get("lockfiles"):
        return '<p class="ctx">Lockfiles read: ' + ", ".join(f"<code>{e(l)}</code>" for l in x["lockfiles"]) + "</p>"
    if t["id"] == "noir-zap":
        app = x.get("app", {})
        eps = x.get("endpoints", [])
        rows = "".join(f'<tr><td><span class="method m-{e(p["method"].lower())}">{e(p["method"])}</span></td>'
                       f'<td><code>{e(p["path"])}</code></td></tr>' for p in eps)
        mode = {"api": "active scan of every route (zap-api-scan)", "baseline": "passive scan (zap-baseline)"}.get(x.get("zap_mode"), "not run")
        return f"""
<p class="ctx">App <code>{e(app.get('url', ''))}</code>: {'reachable (' + e(app.get('detail', '')) + ')' if app.get('reachable') else 'unreachable'} · ZAP: {e(mode)}</p>
<h2 class="sec">Routes mapped by Noir <span class="n">{len(eps)}</span></h2>
{f'<table class="routes"><tbody>{rows}</tbody></table>' if eps else '<p class="empty">No route found.</p>'}
<h2 class="sec">ZAP alerts <span class="n">{len(t['findings'])}</span></h2>"""
    return ""


def build_tool(s: dict, t: dict) -> str:
    meta = TOOLS[t["id"]]
    notes = "".join(f"<li>{e(n)}</li>" for n in t.get("notes", []))
    head_sec = "" if t["id"] == "noir-zap" else f'<h2 class="sec">Results <span class="n">{len(t["findings"])}</span></h2>'
    body = f"""
<p class="back"><a href="../reports.html#{e(t['id'])}">← Reports by tool</a></p>
<section class="hero small">
  <p class="eyebrow">{e(meta['category'])}</p>
  <h1>{e(meta['name'])} {pill(t['status'])}</h1>
  <p class="meta">{e(t['summary'])} · {e(t.get('version', ''))} · {fmt_duration(t.get('duration_s', 0))}</p>
</section>
{links(t, '../', with_detail=False)}
{f'<ul class="notes">{notes}</ul>' if notes else ''}
{tool_extra(t)}
{head_sec}
{findings_table(t['findings'])}
"""
    return page(f"{meta['name']} — {s['project']['name']}", body, 1, "reports", s)


